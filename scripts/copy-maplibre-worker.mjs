/**
 * Copies MapLibre's worker chunks into public/maplibre/.
 *
 * MapLibre 6 locates its worker by reading `import.meta.url` at runtime and
 * gives up with an empty string when that is not an http(s) URL:
 *
 *   function () { let e = import.meta.url;
 *     if (!/^https?:/.test(e)) return ""; ... }
 *
 * Bundlers rewrite `import.meta.url`, so in a Next.js build the worker URL
 * comes back empty, no worker ever starts, and every GeoJSON source stays
 * unloaded: the map renders its background and nothing else. Serving the
 * worker ourselves and setting `config.WORKER_URL` avoids the guess entirely.
 *
 * Runs automatically before dev and build. The copies are generated output and
 * are not committed.
 */
import { copyFile, mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);

// The worker imports "./maplibre-gl-shared.mjs", so both must sit together.
const FILES = ["maplibre-gl-worker.mjs", "maplibre-gl-shared.mjs"];
const OUT_DIR = path.join(process.cwd(), "public", "maplibre");

const pkgPath = require.resolve("maplibre-gl/package.json");
const distDir = path.join(path.dirname(pkgPath), "dist");
const { version } = require(pkgPath);

await mkdir(OUT_DIR, { recursive: true });

for (const file of FILES) {
  await copyFile(path.join(distDir, file), path.join(OUT_DIR, file));
}

// Recorded so a stale copy after a MapLibre upgrade is easy to spot.
await writeFile(
  path.join(OUT_DIR, "VERSION"),
  `maplibre-gl ${version}\ngenerated by scripts/copy-maplibre-worker.mjs\n`,
  "utf8",
);

console.log(`Copied MapLibre ${version} worker chunks to public/maplibre/`);
